export type MessageKey = keyof typeof MESSAGES.ko;

let testLocale: Locale | null = null;

export function setLocaleForTest(locale: Locale | null): void {
  testLocale = locale;
}

export function getLocale(): Locale {
  if (testLocale) return testLocale;
  try {
    if (typeof location !== 'undefined' && location.search) {
      const q = new URLSearchParams(location.search).get('lang');
      if (q === 'en' || q === 'ko') return q;
    }
  } catch {
    /* URL 파라미터 접근 불가 환경 무시 */
  }
  const uiLang = globalThis.chrome?.i18n?.getUILanguage?.();
  if (typeof uiLang === 'string' && uiLang) {
    return uiLang.toLowerCase().startsWith('ko') ? 'ko' : 'en';
  }
  if (typeof document === 'undefined') return 'ko';
  if (typeof navigator !== 'undefined' && typeof navigator.language === 'string') {
    return navigator.language.toLowerCase().startsWith('ko') ? 'ko' : 'en';
  }
  return 'en';
}

export function t(key: MessageKey, ...args: (string | number)[]): string {
  const locale = getLocale();
  let raw = '';
  const hasLangOverride =
    testLocale !== null ||
    (typeof location !== 'undefined' && new URLSearchParams(location.search).has('lang'));
  if (!hasLangOverride && typeof globalThis.chrome?.i18n?.getMessage === 'function') {
    raw = chrome.i18n.getMessage(key) || '';
  }
  if (!raw) raw = MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;
  return args.length ? raw.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? '')) : raw;
}

export function formatCheckpointTime(at: number): string {
  const locale = getLocale();
  const d = new Date(at);
  const tag = locale === 'ko' ? 'ko-KR' : 'en-US';
  const time = d.toLocaleTimeString(tag, { hour: '2-digit', minute: '2-digit', hourCycle: 'h23' });
  if (d.toDateString() === new Date().toDateString()) return time;
  if (locale === 'ko') return `${d.getMonth() + 1}월 ${d.getDate()}일 ${time}`;
  const date = d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
  return `${date}, ${time}`;
}

export function applyI18n(root: ParentNode = document): void {
  const locale = getLocale();
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale;
    document.title = t('pageTitle');
  }
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n as MessageKey);
  }
  for (const el of root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>('[data-i18n-placeholder]')) {
    el.placeholder = t(el.dataset.i18nPlaceholder as MessageKey);
  }
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-aria-label]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel as MessageKey));
  }
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle as MessageKey);
  }
}
